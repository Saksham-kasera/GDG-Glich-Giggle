class TortureModes {
  constructor(app) {
    this.app = app;
    this.currentMode = 'kinetic'; // kinetic | cryo | ballistic | bureaucratic | rotary

    // Cryo Mode State
    this.cryo = {
      temp: 45, // Celsius
      frozen: false,
      iceHealth: 8,
      lastRubTime: Date.now(),
      decayInterval: null
    };

    // Bureaucracy State
    this.signaturePoints = [];
    this.isDrawingSignature = false;
  }

  init() {
    this.initTabs();
    this.initKineticMode();
    this.initCryoMode();
    this.initBallisticMode();
    this.initBureaucracyMode();
    this.initRotaryMode();
  }

  initTabs() {
    const tabs = document.querySelectorAll('.mode-tab');
    tabs.forEach(tab => {
      tab.addEventListener('click', () => {
        tabs.forEach(t => t.classList.remove('active'));
        tab.classList.add('active');
        this.switchMode(tab.dataset.mode);
      });
    });
  }

  switchMode(mode) {
    this.currentMode = mode;
    document.querySelectorAll('.mode-panel').forEach(panel => {
      panel.classList.remove('active');
    });
    const targetPanel = document.getElementById(`panel-${mode}`);
    if (targetPanel) targetPanel.classList.add('active');

    // Announce to Jony Ive commentary
    const commentary = {
      kinetic: "Sir Jony: 'Friction was a compromise of the 19th century. We eliminated it.'",
      cryo: "Sir Jony: 'Thermal acoustics demand physical labor. Earn your sound waves.'",
      ballistic: "Sir Jony: 'Targeting decibels ballistically restores acoustic intentionality.'",
      bureaucratic: "Dr. Malice: 'Sound is a privilege granted by the State, not a right.'",
      rotary: "Sir Jony: 'The circular geometry respects human imperfection by resisting it.'"
    };
    if (this.app.ticker) this.app.ticker.shout(commentary[mode] || "Adjusting acoustic architecture...");

    if (mode === 'cryo') {
      this.startCryoDecay();
    } else {
      this.stopCryoDecay();
    }
  }

  // ==========================================
  // MODE 1: KINETIC (DVD Screensaver Puck)
  // ==========================================
  initKineticMode() {
    const puck = document.getElementById('kinetic-puck');
    const track = document.getElementById('kinetic-track');
    const lockBtn = document.getElementById('btn-kinetic-lock');
    const readout = document.getElementById('kinetic-val');

    // Runaway lock button evasion!
    window.addEventListener('mousemove', (e) => {
      if (this.currentMode === 'kinetic') {
        window.physicsEngine.applyEvasion(lockBtn, e.clientX, e.clientY, 75, 120);
      }
    });

    const loop = () => {
      if (this.currentMode === 'kinetic') {
        const pos = window.physicsEngine.updateBouncySlider(track ? track.clientWidth : 300);
        if (puck) puck.style.left = `${pos}%`;
        if (readout) readout.innerText = `${pos.toFixed(1)}%`;
        if (window.physicsEngine.bouncy.running) {
          this.app.setMasterVolume(pos, false);
        }
      }
      requestAnimationFrame(loop);
    };
    loop();

    if (lockBtn) {
      lockBtn.addEventListener('click', () => {
        if (window.physicsEngine.bouncy.running) {
          const lockedVal = window.physicsEngine.lockBouncySlider();
          lockBtn.innerText = "🔒 LOCKED! (Unlocking in 3s...)";
          lockBtn.classList.add('locked-btn');
          this.app.setMasterVolume(lockedVal, true);
          if (window.soundEngine) window.soundEngine.playCashRegister();

          setTimeout(() => {
            window.physicsEngine.resumeBouncySlider();
            lockBtn.innerText = "🛑 CATCH & LOCK VOLUME";
            lockBtn.classList.remove('locked-btn');
            this.app.toast("⚠️ Thermal slippage detected: Puck resumed motion!", "warning");
          }, 3200);
        }
      });
    }
  }

  // ==========================================
  // MODE 2: CRYO THERMODYNAMIC (Friction Heating)
  // ==========================================
  initCryoMode() {
    const pad = document.getElementById('cryo-rub-zone');
    const iceOverlay = document.getElementById('cryo-ice-overlay');
    const icePickBtn = document.getElementById('btn-ice-pick');
    const tempDisplay = document.getElementById('cryo-temp-display');
    const iceCracks = document.getElementById('ice-cracks');

    let lastX = 0;
    let lastY = 0;

    const handleRub = (x, y) => {
      if (this.cryo.frozen) return;
      const dist = Math.hypot(x - lastX, y - lastY);
      lastX = x;
      lastY = y;

      if (dist > 5) {
        this.cryo.lastRubTime = Date.now();
        // Heat generated by friction
        const heatAdd = Math.min(dist * 0.18, 4.5);
        this.cryo.temp = Math.min(100, this.cryo.temp + heatAdd);
        
        // Volume correlates directly with temperature!
        this.app.setMasterVolume(this.cryo.temp, true);
        this.updateCryoUI();

        // Little visual thermal sparks
        if (Math.random() > 0.6) {
          this.spawnThermalSpark(x, y);
        }
      }
    };

    if (pad) {
      pad.addEventListener('mousemove', (e) => handleRub(e.clientX, e.clientY));
      pad.addEventListener('touchmove', (e) => {
        const touch = e.touches[0];
        handleRub(touch.clientX, touch.clientY);
      }, { passive: true });
    }

    if (icePickBtn) {
      icePickBtn.addEventListener('click', () => {
        if (!this.cryo.frozen) return;
        this.cryo.iceHealth--;
        if (window.soundEngine) window.soundEngine.playIceShatter();
        
        // Show cracked effect
        if (iceCracks) {
          iceCracks.innerText = "❄️".repeat(this.cryo.iceHealth);
        }

        if (this.cryo.iceHealth <= 0) {
          // Thawed!
          this.cryo.frozen = false;
          this.cryo.temp = 25; // Warm up to room temp
          this.cryo.iceHealth = 8;
          if (iceOverlay) iceOverlay.style.display = 'none';
          this.app.toast("💥 ICE SHATTERED! Rub immediately before it refreezes!", "success");
          this.app.setMasterVolume(this.cryo.temp, true);
          this.updateCryoUI();
        }
      });
    }
  }

  startCryoDecay() {
    this.stopCryoDecay();
    this.cryo.decayInterval = setInterval(() => {
      if (this.currentMode !== 'cryo') return;
      if (this.cryo.frozen) return;

      const elapsed = Date.now() - this.cryo.lastRubTime;
      // If idle for more than 1.8 seconds, freeze!
      if (elapsed > 1800) {
        this.cryo.temp = Math.max(0, this.cryo.temp - 6.5);
      } else {
        // Natural convective cooling
        this.cryo.temp = Math.max(0, this.cryo.temp - 2.2);
      }

      this.app.setMasterVolume(this.cryo.temp, false);
      this.updateCryoUI();

      if (this.cryo.temp <= 0 && !this.cryo.frozen) {
        // Freeze event!
        this.cryo.frozen = true;
        this.cryo.iceHealth = 8;
        const iceOverlay = document.getElementById('cryo-ice-overlay');
        const iceCracks = document.getElementById('ice-cracks');
        if (iceOverlay) iceOverlay.style.display = 'flex';
        if (iceCracks) iceCracks.innerText = "❄️❄️❄️❄️❄️❄️❄️❄️";
        if (window.soundEngine) window.soundEngine.playIceShatter();
        this.app.toast("🧊 ABSOLUTE ZERO: The volume track froze! Chisel it out!", "alert");
      }
    }, 200);
  }

  stopCryoDecay() {
    if (this.cryo.decayInterval) {
      clearInterval(this.cryo.decayInterval);
      this.cryo.decayInterval = null;
    }
  }

  updateCryoUI() {
    const tempDisplay = document.getElementById('cryo-temp-display');
    const mercury = document.getElementById('cryo-mercury');
    if (tempDisplay) tempDisplay.innerText = `${this.cryo.temp.toFixed(1)}°C`;
    if (mercury) mercury.style.height = `${Math.min(100, Math.max(0, this.cryo.temp))}%`;
  }

  spawnThermalSpark(x, y) {
    const spark = document.createElement('div');
    spark.className = 'thermal-spark';
    spark.style.left = `${x}px`;
    spark.style.top = `${y}px`;
    document.body.appendChild(spark);
    setTimeout(() => spark.remove(), 400);
  }

  // ==========================================
  // MODE 3: BALLISTIC SLINGSHOT
  // ==========================================
  initBallisticMode() {
    const canvas = document.getElementById('slingshot-canvas');
    if (!canvas) return;

    window.physicsEngine.initSlingshot(
      canvas,
      (val, label) => {
        // Target Hit!
        let newVol = Math.max(0, Math.min(100, this.app.currentVolume + val));
        if (val === 100) newVol = 100; // Jackpot
        this.app.setMasterVolume(newVol, true);
        if (window.soundEngine) {
          if (val > 0) window.soundEngine.playCashRegister();
          else window.soundEngine.playBuzzer();
        }
        this.app.toast(`🎯 TARGET HIT! ${label} (New Volume: ${Math.round(newVol)}%)`, "success");
      },
      () => {
        // Miss! Penalty
        const penalty = -12;
        const newVol = Math.max(0, this.app.currentVolume + penalty);
        this.app.setMasterVolume(newVol, true);
        if (window.soundEngine) window.soundEngine.playBuzzer();
        this.app.toast(`💨 MISSED! Decibel projectile lost in the stratosphere (-12% penalty)`, "alert");
      }
    );
  }

  // ==========================================
  // MODE 4: BUREAUCRATIC FORM 27-B
  // ==========================================
  initBureaucracyMode() {
    const sigCanvas = document.getElementById('signature-canvas');
    const clearSigBtn = document.getElementById('btn-clear-sig');
    const submitBtn = document.getElementById('btn-submit-bureaucracy');
    const permitStatus = document.getElementById('permit-status');

    if (!sigCanvas) return;
    const ctx = sigCanvas.getContext('2d');

    const getPos = (e) => {
      const rect = sigCanvas.getBoundingClientRect();
      const clientX = e.touches ? e.touches[0].clientX : e.clientX;
      const clientY = e.touches ? e.touches[0].clientY : e.clientY;
      return {
        x: clientX - rect.left,
        y: clientY - rect.top
      };
    };

    const startDraw = (e) => {
      this.isDrawingSignature = true;
      const p = getPos(e);
      this.signaturePoints = [p];
      ctx.beginPath();
      ctx.moveTo(p.x, p.y);
    };

    const draw = (e) => {
      if (!this.isDrawingSignature) return;
      const p = getPos(e);
      this.signaturePoints.push(p);
      ctx.strokeStyle = '#00e5ff';
      ctx.lineWidth = 3.5;
      ctx.lineCap = 'round';
      ctx.lineTo(p.x, p.y);
      ctx.stroke();
    };

    const endDraw = () => {
      this.isDrawingSignature = false;
    };

    sigCanvas.addEventListener('mousedown', startDraw);
    sigCanvas.addEventListener('mousemove', draw);
    window.addEventListener('mouseup', endDraw);

    sigCanvas.addEventListener('touchstart', startDraw, { passive: true });
    sigCanvas.addEventListener('touchmove', draw, { passive: true });
    window.addEventListener('touchend', endDraw);

    if (clearSigBtn) {
      clearSigBtn.addEventListener('click', () => {
        ctx.clearRect(0, 0, sigCanvas.width, sigCanvas.height);
        this.signaturePoints = [];
      });
    }

    if (submitBtn) {
      submitBtn.addEventListener('click', () => {
        // Validate circularity of drawn signature!
        const score = this.calculateCircularity(this.signaturePoints);
        const reqVol = parseInt(document.getElementById('bureaucracy-vol-target')?.value || 50);

        if (this.signaturePoints.length < 25) {
          if (window.soundEngine) window.soundEngine.playBuzzer();
          this.app.toast("❌ REJECTED: Signature too brief. Draw a full continuous notarized circle.", "alert");
          return;
        }

        if (score < 88) {
          if (window.soundEngine) window.soundEngine.playBuzzer();
          this.app.toast(`❌ PERMIT DENIED: Signature circularity is only ${score.toFixed(1)}%. Minimum 88% Euclidean perfection required by Article 4!`, "alert");
          if (permitStatus) {
            permitStatus.innerHTML = `<span style="color:#ef4444">❌ REJECTED (Circularity: ${score.toFixed(1)}% / Req: 88%)</span>`;
          }
        } else {
          // Circular enough! But now bureaucratic delay!
          if (window.soundEngine) window.soundEngine.playCashRegister();
          this.app.toast(`✅ SIGNATURE ACCEPTED (${score.toFixed(1)}% circular). Forwarding to Ministry of Acoustics...`, "success");
          if (permitStatus) {
            permitStatus.innerHTML = `<span style="color:#3b82f6">⏳ Processing Docket #88194... Wait 4 business days.</span>`;
          }

          // Offer bribe
          setTimeout(() => {
            if (confirm("Docket #88194 is stalled in review. Would you like to bribe Chief Inspector Malice with 10 volume tokens to approve immediately?")) {
              if (window.soundEngine) window.soundEngine.playAirhorn();
              this.app.setMasterVolume(reqVol, true);
              this.app.toast(`🏛️ PERMIT GRANTED VIA EXPEDITED TARIFF! Volume set to ${reqVol}%`, "success");
              if (permitStatus) {
                permitStatus.innerHTML = `<span style="color:#10b981">APPROVED VIA BRIBERY</span>`;
              }
            } else {
              this.app.toast("⚖️ You chose righteousness. Volume denied.", "alert");
            }
          }, 800);
        }
      });
    }
  }

  calculateCircularity(pts) {
    if (!pts || pts.length < 15) return 0;
    // Calculate centroid
    let sumX = 0, sumY = 0;
    pts.forEach(p => { sumX += p.x; sumY += p.y; });
    const cx = sumX / pts.length;
    const cy = sumY / pts.length;

    // Radii
    const radii = pts.map(p => Math.hypot(p.x - cx, p.y - cy));
    const avgR = radii.reduce((a, b) => a + b, 0) / radii.length;
    if (avgR < 15) return 0;

    // Variance
    const variance = radii.reduce((acc, r) => acc + Math.pow(r - avgR, 2), 0) / radii.length;
    const stdDev = Math.sqrt(variance);

    // Score from 0 to 100
    const score = Math.max(0, 100 - (stdDev / avgR) * 220);
    return score;
  }

  // ==========================================
  // MODE 5: ROTARY MISFORTUNE WHEEL
  // ==========================================
  initRotaryMode() {
    const dial = document.getElementById('rotary-dial');
    const dialVal = document.getElementById('rotary-val');
    let isTurning = false;
    let startAngle = 0;
    let currentAngle = 0;
    let turnsCount = 0;

    if (!dial) return;

    const getAngle = (e) => {
      const rect = dial.getBoundingClientRect();
      const cx = rect.left + rect.width / 2;
      const cy = rect.top + rect.height / 2;
      const clientX = e.touches ? e.touches[0].clientX : e.clientX;
      const clientY = e.touches ? e.touches[0].clientY : e.clientY;
      return Math.atan2(clientY - cy, clientX - cx) * (180 / Math.PI);
    };

    const onStart = (e) => {
      isTurning = true;
      startAngle = getAngle(e) - currentAngle;
    };

    const onMove = (e) => {
      if (!isTurning) return;
      const angle = getAngle(e) - startAngle;
      const delta = angle - currentAngle;
      currentAngle = angle;
      turnsCount++;

      // Slippage trap: every 18th event, oil-slick slip!
      if (turnsCount % 22 === 0) {
        currentAngle -= 65; // slips backward
        if (window.soundEngine) window.soundEngine.playBoing();
        this.app.toast("🛢️ DIAL SLIPPED! Teflon lubrication caused -65° rotary drop!", "warning");
      }

      dial.style.transform = `rotate(${currentAngle}deg)`;

      // Inverted logic: Clockwise DECREASES volume, Counter-clockwise INCREASES!
      const normalized = ((-currentAngle % 360) + 360) % 360;
      const vol = (normalized / 360) * 100;
      this.app.setMasterVolume(vol, false);
      if (dialVal) dialVal.innerText = `${vol.toFixed(1)}%`;
    };

    const onEnd = () => {
      isTurning = false;
    };

    dial.addEventListener('mousedown', onStart);
    window.addEventListener('mousemove', onMove);
    window.addEventListener('mouseup', onEnd);

    dial.addEventListener('touchstart', onStart, { passive: true });
    window.addEventListener('touchmove', onMove, { passive: true });
    window.addEventListener('touchend', onEnd);
  }
}

window.TortureModes = TortureModes;

